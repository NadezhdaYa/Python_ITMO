from rescue_calculator import calculate_rescue_time

def main():
    """Основная функция программы — запрашивает данные у пользователя и выводит результат."""
    print("Расчёт времени спасения утопающего")
    print("=" * 40)

    # Запрос данных у пользователя с преобразованием в тип float
    d1 = float(input("Введите кратчайшее расстояние между спасателем и кромкой воды, d1 (ярды) => "))
    print(d1)

    d2 = float(input("Введите кратчайшее расстояние от утопающего до берега, d2 (футы) => "))
    print(d2)

    h = float(input("Введите боковое смещение между спасателем и утопающим, h (ярды) => "))
    print(h)

    v_sand = float(input("Введите скорость движения спасателя по песку, v_sand (мили в час) => "))
    print(v_sand)

    n = float(input("Введите коэффициент замедления спасателя при движении в воде, n => "))
    print(n)

    theta1 = float(input("Введите направление движения спасателя по песку, theta1 (градусы) => "))
    print(theta1)

    # Вызов функции расчёта из модуля rescue_calculator
    total_time, angle_int = calculate_rescue_time(d1, d2, h, v_sand, n, theta1)

    # Форматированный вывод результата
    print(f"Если спасатель начнёт движение под углом theta1, равным {angle_int} градусам, он достигнет утопающего через {total_time:.1f} секунды")

# Запуск программы
if __name__ == "__main__":
    main()