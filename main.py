from rescue_calculator import (
    convert_yards_to_feet,
    convert_mph_to_fps,
    calculate_rescue_time,
)

# МОДУЛЬНЫЕ ТЕСТЫ

def run_unit_tests():
    """Запускает набор модульных тестов для функций из rescue_calculator."""
    print("\n=== Запуск модульных тестов ===\n")

    # Тест 1: конвертация ярдов в футы
    assert convert_yards_to_feet(1.0) == 3.0, "Тест 1 не пройден: 1 ярд != 3 фута"
    assert convert_yards_to_feet(8.0) == 24.0, "Тест 1 не пройден: 8 ярдов != 24 фута"
    print("✅ Тест 1 пройден: конвертация ярдов → футы")

    # Тест 2: конвертация миль/час → футы/секунду
    # 1 mph = 5280 / 3600 fps ≈ 1.466666...
    expected_fps_1mph = 5280.0 / 3600.0
    assert abs(convert_mph_to_fps(1.0) - expected_fps_1mph) < 1e-9, "Тест 2 не пройден: конвертация mph → fps"
    assert abs(convert_mph_to_fps(5.0) - 5.0 * expected_fps_1mph) < 1e-9, "Тест 2 не пройден: 5 mph"
    print("✅ Тест 2 пройден: конвертация mph → fps")

    # Тест 3: расчёт времени (регрессионный тест на примере из задания)
    # Входные данные из примера:
    d1 = 8.0          # ярды
    d2 = 10.0         # футы
    h = 50.0          # ярды
    v_sand = 5.0      # mph
    n = 2.0           # коэффициент замедления
    theta1 = 39.413   # градусы

    time_sec, angle_int = calculate_rescue_time(d1, d2, h, v_sand, n, theta1)

    # Ожидаемое поведение по заданию: угол округляется до целого, время до 1 знака
    # Мы не можем требовать точного совпадения времени без знания всех деталей округления,
    # но проверяем, что результат «разумен» и угол округлён корректно.
    assert angle_int == 39, f"Тест 3 не пройден: угол должен быть 39, получил {angle_int}"
    assert time_sec > 0, "Тест 3 не пройден: время должно быть положительным"
    print(f"✅ Тест 3 пройден: угол = {angle_int}, время ≈ {time_sec:.1f} сек")

    # Тест 4: крайние случаи (нулевые значения)
    # Если d1 = 0, спасатель уже у кромки воды; x = 0, D1 = 0
    time_zero_d1, angle_zero = calculate_rescue_time(0.0, 10.0, 50.0, 5.0, 2.0, 0.0)
    assert time_zero_d1 > 0, "Тест 4 не пройден: даже при d1=0 время должно быть > 0"
    print("✅ Тест 4 пройден: обработка нулевого d1")

    print("\n=== Все модульные тесты пройдены ===\n")


# Запускаем тесты сразу при импорте/запуске скрипта
run_unit_tests()

# ВЗАИМОДЕЙСТВИЕ С ПОЛЬЗОВАТЕЛЕМ

def get_float_input(prompt: str) -> float:
    """Безопасный ввод вещественного числа с подсказкой."""
    while True:
        try:
            value = float(input(prompt))
            return value
        except ValueError:
            print("Ошибка: введите корректное число.")

def main():
    """Основная функция программы — запрашивает данные у пользователя и выводит результат."""
    print("Расчёт времени спасения утопающего")
    print("=" * 40)

    d1 = get_float_input("Введите кратчайшее расстояние между спасателем и кромкой воды, d1 (ярды) => ")
    print(d1)

    d2 = get_float_input("Введите кратчайшее расстояние от утопающего до берега, d2 (футы) => ")
    print(d2)

    h = get_float_input("Введите боковое смещение между спасателем и утопающим, h (ярды) => ")
    print(h)

    v_sand = get_float_input("Введите скорость движения спасателя по песку, v_sand (мили в час) => ")
    print(v_sand)

    n = get_float_input("Введите коэффициент замедления спасателя при движении в воде, n => ")
    print(n)

    theta1 = get_float_input("Введите направление движения спасателя по песку, theta1 (градусы) => ")
    print(theta1)

    # Вызов функции расчёта из модуля rescue_calculator
    total_time, angle_int = calculate_rescue_time(d1, d2, h, v_sand, n, theta1)

    # Форматированный вывод результата
    print(
        f"Если спасатель начнёт движение под углом theta1, равным {angle_int} градусам, "
        f"он достигнет утопающего через {total_time:.1f} секунды"
    )
# Запуск программы
if __name__ == "__main__":
    main()